classdef SensorDataProcessor
    %SENSORDATAPROCESSOR Pure processing for finite real sensor vectors.
    % This class has no GUI or hardware dependencies.

    methods (Static)
        function summary = summarize(samples)
            if ~(isnumeric(samples) && isreal(samples) && ...
                    isvector(samples) && ~isempty(samples) && ...
                    all(isfinite(samples(:))))
                error('SensorDataProcessor:InvalidSamples', ...
                    'samples 必须是非空有限实数向量。');
            end

            values = double(samples(:));
            summary = struct( ...
                'count', numel(values), ...
                'mean', mean(values), ...
                'min', min(values), ...
                'max', max(values), ...
                'rms', sqrt(mean(values .^ 2)));
        end
    end
end
